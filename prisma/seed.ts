/** מסובב מערך ימינה ב-shift מקומות. */
function rotate<T>(items: T[], shift: number): T[] {
  const n = items.length;
  const by = ((shift % n) + n) % n;
  return [...items.slice(n - by), ...items.slice(0, n - by)];
}

async function main() {
  const totalRegular = questions
    .filter((q) => !q.isBonus)
    .reduce((sum, q) => sum + q.points, 0);

  // מגן על נכונות המבחן: 30 השאלות הרגילות חייבות להסתכם ל-100.
  if (totalRegular !== 100) {
    throw new Error(
      `סכום השאלות הרגילות הוא ${totalRegular} במקום 100 — יש לתקן את ה-seed`,
    );
  }

  const email = (process.env.SEED_ADMIN_EMAIL ?? "admin@example.com").toLowerCase();
  const password = process.env.SEED_ADMIN_PASSWORD ?? "change-me-please";
  const name = process.env.SEED_ADMIN_NAME ?? "מרצה הקורס";

  const passwordHash = await bcrypt.hash(password, 10);
  await prisma.adminUser.upsert({
    where: { email },
    update: { name, passwordHash },
    create: { email, name, passwordHash },
  });
  console.log(`מרצה: ${email}`);

  const slug = "longevity-final-exam-2026";

  // נבנה מחדש בכל הרצה כדי שהשאלות ישקפו תמיד את ה-seed.
  await prisma.exam.deleteMany({ where: { slug } });

  const exam = await prisma.exam.create({
    data: {
      slug,
      title: "מבחן מסכם בקורס: תכנון אריכות ימים",
      courseName: "תכנון אריכות ימים",
      cycle: 2,
      term: "מועד א׳",
      examDate: new Date("2026-07-27T09:00:00+03:00"),
      durationMin: 60,
      singleAttempt: true,
      isPublished: true,
    },
  });

  for (const [index, question] of questions.entries()) {
    // התשובה הנכונה נכתבה למעלה תמיד ראשונה כדי שהקובץ יהיה קריא.
    // כאן היא מפוזרת בין ארבע העמדות בסיבוב דטרמיניסטי, כדי שלא ייווצר
    // דפוס שנבחן יוכל לנחש לפיו.
    const shift = index % question.choices.length;
    const choices = rotate(question.choices, shift);
    const correctIndex = (question.correct + shift) % question.choices.length;

    // שגיאה בסיבוב תסמן תשובה שגויה כנכונה, ולכן נבדקת בכל הרצת seed.
    if (choices[correctIndex] !== question.choices[question.correct]) {
      throw new Error(`סיבוב האפשרויות שיבש את התשובה הנכונה בשאלה ${index + 1}`);
    }

    await prisma.question.create({
      data: {
        examId: exam.id,
        order: index + 1,
        text: question.text,
        points: question.points,
        isBonus: question.isBonus ?? false,
        choices: {
          create: choices.map((text, choiceIndex) => ({
            order: choiceIndex + 1,
            text,
            isCorrect: choiceIndex === correctIndex,
          })),
        },
      },
    });
  }

  console.log(
    `נוצר המבחן "${exam.title}" עם ${questions.length} שאלות (${totalRegular} נק' + בונוס)`,
  );
}

main()
  .catch((error) => {
    console.error(error);
    process.exitCode = 1;
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
